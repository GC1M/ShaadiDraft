const art = (folder: string, widths: Record<string, number>, body = 1): Design['ornaments'] =>
  Object.fromEntries(Object.entries(widths).map(([k, w]) => [k, { src: `${BASE}templates/${folder}/${k}.png`, w: w / body }]))
